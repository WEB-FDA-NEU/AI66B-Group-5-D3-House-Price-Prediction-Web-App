"""Generate frontend/css/luxe-remap.css for the "Bản vẽ" theme (UI-1).

The older stylesheets hard-code hundreds of green and green-grey colours.
Instead of editing those files (owned by several team members, and touched by
open PRs), this script reads them and emits override rules with the SAME
selectors, turned into near-neutral warm greys while keeping each colour's
lightness and alpha (colour on the page comes from photographs and one blue). luxe.css imports the result first, so its hand-written rules win.

Run from the repository root after changing any of the source stylesheets:

    python scripts/build_luxe_remap.py
"""
import colorsys
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / "frontend" / "css"
SOURCES = ["components.css", "design.css", "experience.css", "ux.css", "models.css", "estimate-report.css", "layout.css"]
OUT = ROOT / "luxe-remap.css"
COLOUR_PROPS = re.compile(r"^(color|background|background-color|background-image|border|border-(top|right|bottom|left|block|inline)(-(start|end))?(-color)?|border-color|outline|outline-color|box-shadow|text-shadow|fill|stroke|accent-color|caret-color|text-decoration-color|column-rule|--[\w-]+)$")
HEX = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{4}|[0-9a-fA-F]{3})\b")
WARM_HUE = 36 / 360      # plaster / stone grey
DEEP_HUE = 30 / 360      # ink for very dark tones


def remap_hex(match):
    raw = match.group(1)
    if len(raw) in (3, 4):
        raw = "".join(c * 2 for c in raw)
    r, g, b = (int(raw[i:i + 2], 16) / 255 for i in (0, 2, 4))
    alpha = raw[6:8] if len(raw) == 8 else ""
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if not (75 / 360 < h < 185 / 360) or s < 0.06:
        return match.group(0)                       # not green: leave as is
    hue = DEEP_HUE if l < 0.22 else WARM_HUE
    sat = min(s * 0.3, 0.10 if l > 0.85 else 0.06)
    r2, g2, b2 = colorsys.hls_to_rgb(hue, l, sat)
    return "#" + "".join(f"{round(v * 255):02x}" for v in (r2, g2, b2)) + alpha


def strip_comments(css):
    return re.sub(r"/\*.*?\*/", "", css, flags=re.S)


def rules(css):
    """Yield (media_or_None, selector, body) for flat rules and one level of @media."""
    i = 0
    while i < len(css):
        brace = css.find("{", i)
        if brace < 0:
            return
        head = css[i:brace].strip()
        depth, j = 1, brace + 1
        while depth and j < len(css):
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        body = css[brace + 1:j - 1]
        if head.startswith("@media") or head.startswith("@supports"):
            for _, sel, inner in rules(body):
                yield head, sel, inner
        elif not head.startswith("@"):
            yield None, head, body
        i = j


def main():
    blocks = {}
    count = 0
    for name in SOURCES:
        css = strip_comments((ROOT / name).read_text(encoding="utf-8-sig"))
        for media, selector, body in rules(css):
            out = []
            for decl in body.split(";"):
                if ":" not in decl:
                    continue
                prop, value = (part.strip() for part in decl.split(":", 1))
                if not COLOUR_PROPS.match(prop.lower()) or not HEX.search(value):
                    continue
                new = HEX.sub(remap_hex, value)
                if new != value:
                    out.append(f"{prop}: {new}")
            if out:
                blocks.setdefault(media, []).append(f"{selector} {{ {'; '.join(out)}; }}")
                count += len(out)
    lines = ["/* GENERATED by scripts/build_luxe_remap.py, do not edit by hand.",
             "   Near-neutral greys replacing the green colours hard-coded in: " + ", ".join(SOURCES) + ". */"]
    for media, items in blocks.items():
        if media:
            lines.append(media + " {")
            lines.extend("  " + item for item in items)
            lines.append("}")
        else:
            lines.extend(items)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT.parents[1])}: {count} declarations re-hued")


if __name__ == "__main__":
    main()
